-- Daily briefing self-check: run history + a log of every check / repair / escalation.
-- Additive only: creates two new tables. Nothing existing is altered or deleted.
-- Written by the daily-briefing edge function (service role, bypasses RLS).
-- Readable only by the admin account, via the "Briefing" window in /admin.

create table if not exists public.briefing_runs (
    id            bigint generated by default as identity primary key,
    run_at        timestamptz not null default now(),
    date_key      text        not null,                    -- YYYYMMDD the briefing is for
    status        text        not null check (status in ('healthy', 'repaired', 'degraded', 'failed')),
    briefing      text,                                    -- the text that was pushed (personal schedule!)
    components    jsonb       not null default '[]'::jsonb, -- name / success / error / attempts / durationMs
    push_sent     boolean     not null default false,
    summary       text
);

create table if not exists public.briefing_events (
    id          bigint generated by default as identity primary key,
    run_id      bigint references public.briefing_runs (id) on delete cascade,
    created_at  timestamptz not null default now(),
    kind        text not null check (kind in ('check', 'repair', 'ai', 'escalation')),
    component   text not null,
    severity    text not null check (severity in ('info', 'low', 'medium', 'high', 'critical')),
    outcome     text not null check (outcome in ('ok', 'fixed', 'reported', 'stopped')),
    found       text not null,                             -- what the check found (already redacted)
    action      text not null,                             -- what was changed, or why nothing was
    details     jsonb not null default '{}'::jsonb
);

create index if not exists briefing_runs_run_at_idx    on public.briefing_runs (run_at desc);
create index if not exists briefing_events_run_id_idx  on public.briefing_events (run_id);
create index if not exists briefing_events_created_idx on public.briefing_events (created_at desc);

alter table public.briefing_runs   enable row level security;
alter table public.briefing_events enable row level security;

-- No insert/update/delete policies on purpose: only the service role writes.
revoke all on public.briefing_runs   from anon, authenticated;
revoke all on public.briefing_events from anon, authenticated;
grant select on public.briefing_runs   to authenticated;
grant select on public.briefing_events to authenticated;

drop policy if exists "admin reads briefing runs" on public.briefing_runs;
create policy "admin reads briefing runs"
    on public.briefing_runs for select to authenticated
    using ((select lower(auth.jwt() ->> 'email')) = 'haleannson@gmail.com');

drop policy if exists "admin reads briefing events" on public.briefing_events;
create policy "admin reads briefing events"
    on public.briefing_events for select to authenticated
    using ((select lower(auth.jwt() ->> 'email')) = 'haleannson@gmail.com');

